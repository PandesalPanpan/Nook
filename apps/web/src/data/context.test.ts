import 'fake-indexeddb/auto';
import {afterEach,expect,test} from 'vitest';
import {NookDatabase,Repository} from './repository';
import {search} from './search';
import {exportBackup,restoreBackup} from './backup';
import {effectiveAreaId,createProjectResolver} from '../../../../packages/schemas/src/context';
import {parseEntity} from '../../../../packages/schemas/src/validation';
const databases:NookDatabase[]=[];
test('legacy parent-only subtasks resolve nested context without crossing accounts, deletions or cycles',async()=>{
  const db=new NookDatabase(crypto.randomUUID());databases.push(db);const repo=new Repository(db,'local:parents','client');
  const area=await repo.create('area',{title:'Health',responsibility:'',standards:''});
  const project=await repo.create('project',{title:'Garden',outcome:'',progress:0,areaId:area.id});
  const parent=await repo.create('task',{title:'Plant',completed:false,projectId:project.id});
  const child=await repo.create('task',{title:'Water',completed:false,parentTaskId:parent.id});
  const leaf=await repo.create('task',{title:'Check soil',completed:false,parentTaskId:child.id});
  const records=[project,parent,child,leaf];
  expect(effectiveAreaId(leaf,records)).toBe(area.id);
  expect(createProjectResolver(records,repo.accountId)(leaf)).toBe(project.id);
  expect((await search(repo,'project:Garden soil')).map(r=>r.id)).toEqual([leaf.id]);
  expect(createProjectResolver([project,{...parent,deleted:true},child],repo.accountId)(leaf)).toBeUndefined();
  expect(createProjectResolver([project,{...parent,accountId:'bob'},child],repo.accountId)(leaf)).toBeUndefined();
  expect(createProjectResolver([{...parent,data:{title:'Cycle',completed:false,parentTaskId:child.id}},child],repo.accountId)(child)).toBeUndefined();
  expect(createProjectResolver(records,repo.accountId)({...leaf,data:{...leaf.data,projectId:'explicit'}})).toBe('explicit');
  expect((await search(repo,'area:Health soil')).map(r=>r.id)).toEqual([leaf.id]);
  expect(effectiveAreaId(leaf,[project,{...parent,accountId:'bob'},child])).toBeUndefined();
  expect(effectiveAreaId(leaf,[project,{...parent,deleted:true},child])).toBeUndefined();
  expect(effectiveAreaId({...child,data:{...child.data,projectId:'missing'}},records)).toBeUndefined();
  expect(effectiveAreaId(child,[{...parent,data:{title:'Cycle',completed:false,parentTaskId:child.id}},child])).toBeUndefined();
  expect(effectiveAreaId({...leaf,data:{...leaf.data,areaId:'explicit'}},records)).toBe('explicit');
});
afterEach(async()=>{await Promise.all(databases.splice(0).map(db=>db.delete()));});
test('resource context survives backup and Area search inherits a Project with explicit overrides',async()=>{
  const db=new NookDatabase(crypto.randomUUID());databases.push(db);const repo=new Repository(db,'local:context','client');
  const area=await repo.create('area',{title:'Health',responsibility:'',standards:''});
  const other=await repo.create('area',{title:'Work',responsibility:'',standards:''});
  const project=await repo.create('project',{title:'Garden',outcome:'',progress:0,areaId:area.id});
  const resource=await repo.create('resource',{title:'Seed guide',description:'Reference',projectId:project.id});
  expect(parseEntity({...resource,data:{title:'Legacy',description:''}}).kind).toBe('resource');
  expect(effectiveAreaId(resource,[{...project,accountId:'bob'}])).toBeUndefined();
  expect((await search(repo,'area:Health Seed')).map(r=>r.id)).toEqual([resource.id]);
  await repo.update(resource.id,r=>r.kind==='resource'?{...r,data:{...r.data,areaId:other.id}}:r);
  expect(await search(repo,'area:Health Seed')).toEqual([]);
  expect((await search(repo,'area:Work Seed')).map(r=>r.id)).toEqual([resource.id]);
  const restored=new Repository(db,'restored','client');await restoreBackup(restored,await exportBackup(repo));
  expect((await restored.list('resource'))[0].data).toMatchObject({projectId:project.id,areaId:other.id});
  expect(()=>parseEntity({...resource,data:{...resource.data,areaId:'unsafe/path'}})).toThrow();
});
